"""Generates lib/features/messaging/utils/emoji_catalog_data.dart from Unicode's
emoji-test.txt (https://unicode.org/Public/emoji/16.0/emoji-test.txt).

Every fully-qualified emoji up to the version in MAX_VERSION is listed in
Unicode's own group order. Skin-tone variants are folded into their base
entry's `tones` list (light → dark), so the picker can offer them without
listing them five times. The short names and search keywords curated in
tool/emoji_shortnames.py take precedence over the names derived from the
CLDR description, so `:joy:`, `:thumbsup:` and friends keep working.

Run from the repository root:
    python -I tool/make_emoji_catalog.py path/to/emoji-test.txt
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from emoji_shortnames import SHORTNAMES  # noqa: E402

MAX_VERSION = 15.1

GROUPS = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "nature",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}
TONES = [
    "light skin tone",
    "medium-light skin tone",
    "medium skin tone",
    "medium-dark skin tone",
    "dark skin tone",
]
LINE = re.compile(
    r"^([0-9A-F ]+?)\s*;\s*(fully-qualified|minimally-qualified|unqualified|component)"
    r"\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.*)$"
)


def slug(name):
    s = name.lower()
    s = s.replace("’", "").replace("'", "")
    s = re.sub(r"[^a-z0-9]+", "_", s)
    return s.strip("_")


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main(path):
    entries = []  # dicts in file order
    by_name = {}  # CLDR name → entry (for tone folding)
    group = None
    for raw in Path(path).read_text(encoding="utf-8").splitlines():
        if raw.startswith("# group:"):
            group = raw.split(":", 1)[1].strip()
            continue
        if not raw or raw.startswith("#"):
            continue
        m = LINE.match(raw)
        if not m or m.group(2) != "fully-qualified":
            continue
        category = GROUPS.get(group)
        if category is None:
            continue
        if float(m.group(4)) > MAX_VERSION:
            continue
        char, cldr = m.group(3), m.group(5).strip()
        # Fold "X: medium skin tone" into X. Two-tone pairs ("X: light skin
        # tone, dark skin tone") are left out; only uniform tones are offered.
        if ":" in cldr:
            base, _, suffix = cldr.rpartition(":")
            suffix = suffix.strip()
            if suffix in TONES:
                parent = by_name.get(base.strip())
                if parent is not None:
                    parent["tones"][TONES.index(suffix)] = char
                continue
            if "skin tone" in suffix:
                continue
        entry = {"char": char, "cldr": cldr, "category": category, "tones": [None] * 5}
        entries.append(entry)
        by_name[cldr] = entry

    seen = set()
    lines = [
        "// GENERATED by tool/make_emoji_catalog.py from Unicode emoji-test.txt",
        "// (emoji up to E%s). Do not edit by hand." % MAX_VERSION,
        "",
        "part of 'emoji_catalog.dart';",
        "",
        "const List<EmojiEntry> kEmojiCatalog = [",
    ]
    for e in entries:
        derived = slug(e["cldr"])
        curated = SHORTNAMES.get(e["char"]) or SHORTNAMES.get(e["char"].replace("️", ""))
        if curated:
            name, extra = curated
            keywords = " ".join(dict.fromkeys((derived.replace("_", " ") + " " + extra).split()))
        else:
            name, keywords = derived, derived.replace("_", " ")
        base = name
        n = 2
        while name in seen:
            name = f"{base}_{n}"
            n += 1
        seen.add(name)
        tones = e["tones"]
        tone_arg = ""
        if all(tones):
            tone_arg = ", [" + ", ".join(dart_str(t) for t in tones) + "]"
        lines.append(
            "  EmojiEntry(%s, %s, EmojiCategory.%s, %s%s),"
            % (dart_str(e["char"]), dart_str(name), e["category"], dart_str(keywords), tone_arg)
        )
    lines.append("];")
    out = Path("lib/features/messaging/utils/emoji_catalog_data.dart")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    toned = sum(1 for e in entries if all(e["tones"]))
    print(f"{len(entries)} emoji ({toned} with skin tones) -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
